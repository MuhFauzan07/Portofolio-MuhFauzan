const views = [...document.querySelectorAll("[data-route]")];
const navigationLinks = [...document.querySelectorAll("[data-nav]")];
const navigation = document.querySelector(".primary-navigation");
const menuToggle = document.querySelector(".menu-toggle");
const detailContent = document.querySelector("#project-detail-content");

function getRoute() {
  const [page = "home", project = ""] = window.location.hash.replace(/^#\/?/, "").split("/");
  return { page, project };
}

function renderProject(projectId) {
  const project = projects[projectId];
  if (!project) {
    window.location.hash = "projects";
    return false;
  }

  const links = project.links.map((link) =>
    `<a class="button button-outline" href="${link.href}" target="_blank" rel="noreferrer">${link.label}</a>`
  ).join("");
  const highlights = project.highlights.map((item) => `<li>${item}</li>`).join("");
  const metadata = [
    project.role && `<div><span class="fact-index">My Role</span><strong>${project.role}</strong></div>`,
    project.tools && `<div><span class="fact-index">Tools</span><strong>${project.tools}</strong></div>`,
    project.language && `<div><span class="fact-index">Language</span><strong>${project.language}</strong></div>`
  ].filter(Boolean).join("");
  const gallery = project.gallery.map(([src, alt]) =>
    `<figure class="detail-image"><img src="assets/${src}" alt="${alt}"></figure>`
  ).join("");
  const description = project.description ? `<p class="detail-description">${project.description}</p>` : "";

  detailContent.innerHTML = `
    <a class="back-link" href="#projects" aria-label="Kembali ke Projects"><img src="assets/back-arrow.png" alt=""></a>
    <div class="project-detail-layout">
      <div class="detail-copy">
        <p class="detail-category">${project.category}</p>
        <h1>${project.title}</h1>
        ${description}
        <h2 class="detail-subheading">KEY FEATURES</h2>
        <ul class="detail-highlights">${highlights}</ul>
        <div class="project-meta">${metadata}</div>
        <div class="detail-links">${links}</div>
      </div>
      <div class="detail-gallery detail-gallery--${projectId}">${gallery}</div>
    </div>`;
  return true;
}

function updatePage() {
  if (window.location.hash === "#main") return;

  const { page, project } = getRoute();
  const route = page === "project" ? "project" : page;

  if (!views.some((view) => view.dataset.route === route)) {
    window.location.hash = "home";
    return;
  }
  if (route === "project" && !renderProject(project)) return;

  for (const view of views) {
    const isActive = view.dataset.route === route;
    view.hidden = !isActive;
    view.classList.toggle("is-active", isActive);
  }
  for (const link of navigationLinks) {
    const isCurrent = link.dataset.nav === route || (route === "project" && link.dataset.nav === "projects");
    if (isCurrent) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  }

  menuToggle.setAttribute("aria-expanded", "false");
  navigation.classList.remove("is-open");
  const behavior = window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth";
  window.scrollTo({ top: 0, behavior });
}

menuToggle.addEventListener("click", () => {
  const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isExpanded));
  navigation.classList.toggle("is-open", !isExpanded);
});

window.addEventListener("hashchange", updatePage);
updatePage();
